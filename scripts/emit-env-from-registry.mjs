#!/usr/bin/env node
// Generates the per-environment host configuration of the platform from the canonical registry (ADR-059), using the registry tool's --emit mode.
//
//   node scripts/emit-env-from-registry.mjs --env test|pilot|prod|all [--out <dir>] [--check] [--tool <path to validate-registry.mjs>]
//
// Output per environment, in <out>/<env>/ (default .generated/env, git-ignored; never edit by hand, never commit):
//   api.env              host variables of the API container: CORS_ORIGINS, OIDC_ISSUER, PUBLIC_BASE_URL, PUBLIC_APP_URL, WEB_BASE_URL, SITE_CANONICAL_HOST,
//                        WIDGET_HOST, WIDGET_EMBED_HOST, KIORLY_BASE_URL, plus KX_ENV, KX_ENV_TAG, KX_PLANE, KX_REGISTRY_HASH
//   web.build.env        VITE_* values baked into the patient web build
//   ops.build.env        VITE_* values baked into the ops console build
//   oidc-redirects.json  redirect, post-logout and back-channel URIs per OIDC client (for the identity provider configuration)
// `--check` regenerates in memory and exits 1 when the files on disk differ (drift guard for CI). No network, no AWS, no secrets.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const val = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : undefined; };
const flag = (n) => args.includes(n);

const TOOL = path.resolve(val('--tool') ?? process.env.REGISTRY_TOOL ?? path.join(here, '..', '..', '_docs', 'registry', 'validate-registry.mjs'));
const REGISTRY = process.env.REGISTRY_FILE ?? path.join(path.dirname(TOOL), 'service-url-registry.yaml');
const OUT = path.resolve(val('--out') ?? path.join(here, '..', '.generated', 'env'));
const ENVS = ['test', 'pilot', 'prod'];

function fail(msg) { console.error(`emit-env-from-registry: ${msg}`); process.exit(2); }
if (!fs.existsSync(TOOL)) fail(`registry tool not found at ${TOOL} (pass --tool or set REGISTRY_TOOL)`);

function emit(kind, envId) {
  const r = spawnSync(process.execPath, [TOOL, '--emit', kind, '--env', envId], { encoding: 'utf8', env: { ...process.env, REGISTRY_FILE: REGISTRY } });
  if (r.status !== 0) fail(`registry tool failed for --emit ${kind} --env ${envId}: ${r.stderr || r.stdout}`);
  // the tool prints a final "registry OK" status line after the emitted rows
  return r.stdout.split('\n').filter((l) => l && !l.startsWith('registry OK'));
}
function emitJson(kind, envId) {
  const r = spawnSync(process.execPath, [TOOL, '--emit', kind, '--env', envId], { encoding: 'utf8', env: { ...process.env, REGISTRY_FILE: REGISTRY } });
  if (r.status !== 0) fail(`registry tool failed for --emit ${kind}: ${r.stderr}`);
  return JSON.parse(r.stdout.slice(0, r.stdout.lastIndexOf('registry OK')).trim());
}

const { load } = await import(pathToFileURL(TOOL).href);
const reg = load(REGISTRY);
const hash = createHash('sha256').update(fs.readFileSync(REGISTRY)).digest('hex').slice(0, 16);

/** service id -> { VAR: value } for one environment, from `--emit env`. */
function envMap(envId) {
  const m = {};
  for (const line of emit('env', envId)) {
    const [svc, kv] = line.split('\t');
    const i = kv.indexOf('=');
    (m[svc] ??= {})[kv.slice(0, i)] = kv.slice(i + 1);
  }
  return m;
}
const HEADER = (envId, what) => `# GENERATED by scripts/emit-env-from-registry.mjs from _docs/registry/service-url-registry.yaml (hash ${hash}), environment ${envId}: ${what}.\n# Do not edit by hand and do not commit. A change goes through the registry pull request. Contains no secret.\n`;
const lines = (o) => Object.entries(o).map(([k, v]) => `${k}=${v}`).join('\n') + '\n';

export function build(envId) {
  const env = reg.environments.find((e) => e.id === envId);
  if (!env) fail(`environment ${envId} not in the registry`);
  const m = envMap(envId);
  const api = m['kiorex.api'] ?? fail(`kiorex.api has no env block in ${envId}`);
  const mkt = m['kiorex.marketplace'] ?? {};
  const admin = m['kiorex.admin'] ?? {};
  const clinics = m['kiorly.clinics'] ?? {};
  const apiEnv = {
    KX_ENV: envId, KX_ENV_TAG: env.tag, KX_PLANE: env.plane, KX_REGISTRY_HASH: hash,
    ...api,
    ...(mkt.WEB_BASE_URL ? { WEB_BASE_URL: mkt.WEB_BASE_URL } : {}),
    ...(mkt.SITE_CANONICAL_HOST ? { SITE_CANONICAL_HOST: mkt.SITE_CANONICAL_HOST } : {}),
    ...(api.WIDGET_HOST ? { WIDGET_EMBED_HOST: `https://${api.WIDGET_HOST}`, WIDGET_PRODUCTION_HOST: api.WIDGET_HOST } : {}),
  };
  const webEnv = { VITE_OIDC_AUTHORITY: mkt.VITE_OIDC_AUTHORITY, ...(clinics.APP_WEB_URL ? { VITE_KIORLY_CLINICS_URL: clinics.APP_WEB_URL } : {}) };
  const opsEnv = { VITE_OIDC_AUTHORITY: admin.VITE_OIDC_AUTHORITY, ...(mkt.SITE_CANONICAL_HOST ? { VITE_SITE_CANONICAL_HOST: mkt.SITE_CANONICAL_HOST } : {}) };
  const issuerEnv = reg.oidc.issuer_env[envId];
  const redirects = emitJson('redirects', issuerEnv ?? envId).filter((r) => r.env === envId);
  return {
    'api.env': HEADER(envId, 'API container host configuration') + lines(apiEnv),
    'web.build.env': HEADER(envId, 'patient web build') + lines(Object.fromEntries(Object.entries(webEnv).filter(([, v]) => v))),
    'ops.build.env': HEADER(envId, 'ops console build') + lines(Object.fromEntries(Object.entries(opsEnv).filter(([, v]) => v))),
    'oidc-redirects.json': JSON.stringify({ generated_from: 'service-url-registry.yaml', registry_hash: hash, env: envId, issuer_env: issuerEnv, clients: redirects }, null, 2) + '\n',
  };
}

const wanted = (val('--env') ?? 'all') === 'all' ? ENVS : [val('--env')];
for (const e of wanted) if (!ENVS.includes(e)) fail(`--env must be one of ${ENVS.join(', ')} or all`);
let drift = 0;
for (const e of wanted) {
  const files = build(e);
  for (const [name, content] of Object.entries(files)) {
    const p = path.join(OUT, e, name);
    if (flag('--check')) {
      const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
      if (cur !== content) { drift++; console.error(`drift: ${path.relative(process.cwd(), p)}`); }
    } else { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, content); console.log(`wrote ${path.relative(process.cwd(), p)}`); }
  }
}
if (drift) process.exit(1);
