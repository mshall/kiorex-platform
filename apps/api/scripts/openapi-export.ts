import 'reflect-metadata';
import { NestFactory } from '@nestjs/core';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

async function main() {
  process.env.JOBS_ENABLED = 'false';
  const { AppModule } = await import('../src/app.module');
  const { buildOpenApi, setupApp } = await import('../src/app.setup');
  const app = await NestFactory.create(AppModule, { logger: false, rawBody: true });
  setupApp(app);
  await app.init();
  const doc = buildOpenApi(app);
  const out = join(__dirname, '..', 'openapi', 'kiorex-api.v1.openapi.json');
  mkdirSync(join(__dirname, '..', 'openapi'), { recursive: true });
  writeFileSync(out, JSON.stringify(doc, null, 2) + '\n');
  const routes = Object.entries(doc.paths).flatMap(([p, v]) => Object.entries(v as object).map(([m, o]: [string, any]) => ({ m: m.toUpperCase(), p: '/api/v1' + p, s: o.summary ?? '', tags: o.tags?.[0] ?? '' })));
  const byTag = new Map<string, typeof routes>();
  for (const r of routes) byTag.set(r.tags, [...(byTag.get(r.tags) ?? []), r]);
  let md = '# Kiorex API routes\n\nGenerated by `npm run openapi:export -w apps/api` (do not edit). Base: `http://localhost:4000/api/v1`. Auth: `Authorization: Bearer <Kiorex Passport access token>` unless noted. Errors: `{ code, message, ...extra }`. Flag OFF: `403 { code: "FEATURE_DISABLED", key, scope }`.\n\nFull schema: `apps/api/openapi/kiorex-api.v1.openapi.json`.\n';
  for (const [tag, rs] of [...byTag].sort()) {
    md += `\n## ${tag}\n\n| Method | Path | Summary |\n|---|---|---|\n` + rs.map((r) => `| ${r.m} | \`${r.p}\` | ${r.s} |`).join('\n') + '\n';
  }
  mkdirSync(join(__dirname, '..', '..', '..', 'Docs'), { recursive: true });
  writeFileSync(join(__dirname, '..', '..', '..', 'Docs', 'API-ROUTES.generated.md'), md);
  console.log(`openapi: ${routes.length} operations -> ${out}`);
  await app.close();
}
void main();
